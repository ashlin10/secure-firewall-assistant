import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(process.argv[2],'utf8');
const source=html.match(/<script>([\s\S]*?)<\/script>/)[1];
assert.ok(!html.includes('id="domain"') && !html.includes('id="ca"'));
function card(fetchImpl=async()=>({ok:true,json:async()=>({ok:true,alias:'fixture'})})){
  const nodes=new Map(),messages=[],calls=[],events={},timers=new Map();let timerId=0;
  const node=id=>{
    if(!nodes.has(id))nodes.set(id,{value:'',hidden:true,disabled:false,textContent:'',dataset:{},scrollIntoView(){},listeners:{},addEventListener(name,fn){this.listeners[name]=fn}});
    return nodes.get(id);
  };
  const parent={postMessage(message){messages.push(message)}};
  const window={parent,addEventListener(name,fn){events[name]=fn}};
  const context={window,document:{getElementById:node},URL,JSON,Date,AbortController,
    setTimeout(fn,ms){timers.set(++timerId,{fn,ms});return timerId},clearTimeout(id){timers.delete(id)},
    async fetch(url,opts){calls.push({url,opts});return fetchImpl(url,opts)}};
  vm.runInNewContext(source,context);
  const deliver=message=>events.message({source:parent,data:{jsonrpc:'2.0',...message}});
  const result=(id,data)=>deliver({id,result:{structuredContent:data}});
  const setup=()=>deliver({method:'ui/notifications/tool-result',params:{_meta:{enrollment:{endpoint:'http://127.0.0.1:50123/enroll/'+'a'.repeat(32),authorization:'synthetic-authorization',alias:'fixture',kind:'fmc',address:'https://fmc.example.invalid',username:'tester',expires:Date.now()/1000+600}}}});
  const submit=()=>{node('password').value='synthetic-private-value';node('repeat').value='synthetic-private-value';return node('form').listeners.submit({preventDefault(){}})};
  const noLeaks=()=>assert.equal(JSON.stringify(messages).includes('synthetic-private-value'),false);
  return {node,messages,calls,timers,deliver,result,setup,submit,noLeaks};
}
const c=card();
assert.equal(c.messages[0].method,'ui/initialize');
c.deliver({id:1,result:{hostContext:{}}});
c.deliver({method:'ui/notifications/tool-result',params:{structuredContent:{status:'enter_device_details'}}});
assert.equal(c.node('deviceForm').hidden,false);
c.node('deviceAlias').value='fixture';c.node('deviceAddress').value='https://fmc.example.invalid';c.node('deviceUsername').value='tester';
c.node('deviceForm').listeners.submit({preventDefault(){}});
assert.equal(c.messages.find(m=>m.method==='tools/call').params.name,'start_enrollment');
c.setup();
c.node('password').value='synthetic-private-value';c.node('repeat').value='mismatch';
await c.node('form').listeners.submit({preventDefault(){}});
assert.equal(c.calls.length,0);assert.equal(c.node('password').value,'');
await c.submit();
assert.deepEqual(Object.keys(JSON.parse(c.calls[0].opts.body)).sort(),['password','repeat']);
assert.equal(c.calls[0].opts.credentials,'omit');
assert.equal(c.node('password').value,'');assert.equal(c.node('repeat').value,'');
assert.ok(c.messages.some(m=>m.params?.name==='enrollment_status'));
assert.ok(!c.messages.some(m=>m.params?.name==='connect_fmc'));
c.result(11,{status:'enrolled'});
assert.equal(c.node('form').hidden,true);
assert.ok(c.node('status').textContent.includes('saved successfully'));
assert.ok(c.messages.some(m=>m.params?.name==='connect_fmc'));
c.result(12,{target:'fixture',server_version:'10.5.0',domain:'Global'});
assert.ok(c.node('status').textContent.includes('connection verified'));c.noLeaks();
const lost=card(async()=>{throw new Error('network blocked')});lost.setup();await lost.submit();
assert.equal(lost.node('save').disabled,true);assert.equal(lost.node('check').hidden,false);
assert.ok(lost.node('status').textContent.includes('did not arrive'));
lost.node('check').listeners.click();lost.result(11,{status:'saving'});
assert.ok(lost.node('status').textContent.includes('still in progress'));assert.equal(lost.node('save').disabled,true);
lost.node('check').listeners.click();lost.result(11,{status:'enrolled'});
lost.result(12,{ok:false,error:{code:'tls_error'}});
assert.ok(lost.node('status').textContent.includes('saved successfully'));assert.ok(lost.node('status').textContent.includes('could not be verified'));lost.noLeaks();
const waiting=card(async()=>{throw new Error('blocked')});waiting.setup();await waiting.submit();waiting.node('check').listeners.click();waiting.result(11,{status:'waiting'});
assert.equal(waiting.node('save').disabled,false);assert.equal(waiting.node('form').hidden,false);
const hanging=card((url,opts)=>new Promise((resolve,reject)=>opts.signal.addEventListener('abort',()=>reject(new Error('timeout')))));
hanging.setup();const pending=hanging.submit();[...hanging.timers.values()].find(t=>t.ms===20000).fn();await pending;
assert.ok(hanging.node('status').textContent.includes('did not arrive'));hanging.noLeaks();
